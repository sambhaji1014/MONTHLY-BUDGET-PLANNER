/**
 * Returns user-specific seed data or a clean blank profile for new accounts.
 * - Sambhaji Jadhav: 120,000 monthly income, 11 categories, 10 transactions.
 * - Priya Sharma: 85,000 monthly income, 8 categories, 6 transactions.
 * - Guest: Sandbox exploration dataset.
 * - New Account: BLANK profile (all lists empty, income 0, isOnboarded: false).
 */
export const getSeedUserData = (email?: string) => {
  if (!email) {
    return {
      monthlyIncome: 120000,
      categories: initialCategories,
      transactions: initialTransactions,
      goals: initialGoals,
      bills: initialBills,
      isOnboarded: true,
    };
  }

  const norm = email.trim().toLowerCase();
  if (norm === 'sambhaji.jadhav@example.com' || norm === 'jadhav@wealthwise.com') {
    return {
      monthlyIncome: 120000,
      categories: initialCategories,
      transactions: initialTransactions,
      goals: initialGoals,
      bills: initialBills,
      isOnboarded: true,
    };
  }
  if (norm === 'priya.sharma@example.com') {
    return {
      monthlyIncome: 85000,
      categories: priyaCategories,
      transactions: priyaTransactions,
      goals: priyaGoals,
      bills: priyaBills,
      isOnboarded: true,
    };
  }
  if (norm.includes('guest') || norm.includes('sandbox')) {
    return {
      monthlyIncome: 120000,
      categories: initialCategories,
      transactions: initialTransactions,
      goals: initialGoals,
      bills: initialBills,
      isOnboarded: true,
    };
  }

  // Brand new account: strictly start with a blank profile!
  return {
    monthlyIncome: 0,
    categories: [] as BudgetCategory[],
    transactions: [] as Transaction[],
    goals: [] as SavingsGoal[],
    bills: [] as BillSubscription[],
    isOnboarded: false,
  };
};
